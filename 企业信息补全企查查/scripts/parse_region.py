def parse_addr(addr: str):
    addr = (addr or '').strip()
    if not addr:
        return ('', '', '')
    if addr in OVERSEAS:
        return ('', '', '')
    for mu in MUNICIPAL:
        if addr.startswith(mu):
            rest = addr[len(mu):]
            m = re.match(r'(.+?(?:区|县|新区))', rest)
            return (mu, mu, m.group(1) if m else '')
    for p in PROVINCES:
        if addr.startswith(p):
            rest = addr[len(p):]
            m = re.match(r'(.+?(?:自治州|地区|盟|市))', rest)
            city = m.group(1) if m else ''
            rest2 = rest[len(city):] if city else rest
            m2 = re.match(r'(.{2,}?(?:新区|区|县|市))', rest2)
            return (p, city, m2.group(1) if m2 else '')
    m = re.match(r'(.+?(?:自治州|地区|盟|市|县|州))', addr)
    if m:
        head = m.group(1)
        for c in CITY2PROV:
            if head == c or head.startswith(c):
                prov = CITY2PROV[c]
                city = head
                rest = addr[len(city):]
                m2 = re.match(r'(.{2,}?(?:新区|区|县|市))', rest)
                dist = m2.group(1) if m2 else ''
                return (prov, city, dist)
        return ('', '', head)
    return ('', '', '')


